// Raiden S0-1 — ESP32-S3FN8, 8 MB embedded flash, no PSRAM.
// The single USB-C port is wired directly to the chip's native USB
// (GPIO19 = D-, GPIO20 = D+); there is no USB-to-UART bridge on the board.
// GPIO0  -> BOOT button, GPIO48 -> user LED (active high, 470R in series).
// Not broken out: GPIO0, GPIO19, GPIO20, GPIO45, GPIO46, GPIO48.
// GPIO15/GPIO16 drive the 32.768 kHz crystal and are not available.

static const uint8_t LED_BUILTIN = 48;
#define BUILTIN_LED LED_BUILTIN  // backward compatibility
#define LED_BUILTIN LED_BUILTIN  // allow testing #ifdef LED_BUILTIN

